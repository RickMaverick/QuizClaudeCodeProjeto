import type { Level, Question } from "@/types/quiz";

export const DOCS_BASE_URL = "https://code.claude.com/docs/en";

// Data da última revisão do banco contra a documentação oficial (PRD §3.2).
const VERIFIED_AT = "";

function q(
  id: string,
  level: Level,
  topic: string,
  statement: string,
  answer: boolean,
  explanation: string,
  docPath: string,
): Question {
  return {
    id,
    level,
    topic,
    statement,
    answer,
    explanation,
    docUrl: `${DOCS_BASE_URL}${docPath}`,
    active: true,
    verifiedAt: VERIFIED_AT,
  };
}

